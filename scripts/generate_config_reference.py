"""Generate the configuration reference tables in README.md from the settings model.

The parameter tables are rendered from the pydantic models in
`flex_dep_opt.config.settings` (name, type, default, constraints and the
`Field(description=...)` text) and written between two marker comments in the
README, so the documentation cannot drift from the code.

Usage:
    python scripts/generate_config_reference.py           # rewrite the block in README.md
    python scripts/generate_config_reference.py --check   # exit 1 if the block is stale
"""

from __future__ import annotations

import argparse
import sys
import types
from pathlib import Path
from typing import Any, Literal, Union, get_args, get_origin

import annotated_types as at
from pydantic import BaseModel
from pydantic.fields import FieldInfo

from flex_dep_opt.config.settings import Settings

README_PATH = Path(__file__).resolve().parent.parent / "README.md"
START_MARKER = (
    "<!-- config-reference:start (generated by scripts/generate_config_reference.py, do not edit) -->"
)
END_MARKER = "<!-- config-reference:end -->"


def _is_model(annotation: Any) -> bool:
    return isinstance(annotation, type) and issubclass(annotation, BaseModel)


def _type_text(annotation: Any) -> str:
    origin = get_origin(annotation)
    if origin is Literal:
        return " / ".join(f"`{v}`" for v in get_args(annotation))
    if origin in (Union, types.UnionType):
        args = [a for a in get_args(annotation) if a is not type(None)]
        return ", ".join(_type_text(a) for a in args) + ", optional"
    return annotation.__name__


def _constraints_text(field: FieldInfo) -> str:
    symbols = {at.Ge: ("ge", "≥"), at.Gt: ("gt", ">"), at.Le: ("le", "≤"), at.Lt: ("lt", "<")}
    parts = [
        f"{symbol} {getattr(meta, attr):g}"
        for meta in field.metadata
        for cls, (attr, symbol) in symbols.items()
        if isinstance(meta, cls)
    ]
    return ", ".join(parts)


def _default_text(field: FieldInfo) -> str:
    if field.is_required():
        return "required"
    if field.default is None:
        return "unset"
    if isinstance(field.default, bool):
        return f"`{str(field.default).lower()}`"
    if isinstance(field.default, str):
        return f'`"{field.default}"`'
    return f"`{field.default}`"


def _collect(model: type[BaseModel], prefix: str, group: str, groups: dict[str, list[tuple[str, FieldInfo]]]):
    """Sort all leaf parameters into table groups (one per section, optimization split by sub-section)."""
    for name, field in model.model_fields.items():
        path = f"{prefix}{name}"
        if _is_model(field.annotation):
            sub_group = path if prefix in ("", "optimization.") else group
            groups.setdefault(sub_group, [])
            _collect(field.annotation, f"{path}.", sub_group, groups)
        else:
            groups.setdefault(group, []).append((path, field))


def _group_description(path: str) -> str:
    model: type[BaseModel] = Settings
    field: FieldInfo | None = None
    for part in path.split("."):
        field = model.model_fields[part]
        model = field.annotation
    return field.description or ""


def render() -> str:
    """Return the Markdown block with one parameter table per settings section."""
    groups: dict[str, list[tuple[str, FieldInfo]]] = {}
    _collect(Settings, "", "", groups)

    lines: list[str] = []
    for group, rows in groups.items():
        if not rows:
            continue
        lines += [
            f"**`{group}`**: {_group_description(group)}",
            "",
            "| Parameter | Type | Default | Description |",
            "|---|---|---|---|",
        ]
        for path, field in rows:
            type_text = _type_text(field.annotation)
            constraints = _constraints_text(field)
            if constraints:
                type_text += f" ({constraints})"
            description = (field.description or "").replace("|", "\\|")
            lines.append(f"| `{path}` | {type_text} | {_default_text(field)} | {description} |")
        lines.append("")
    return "\n".join(lines).rstrip("\n")


def split_readme(text: str) -> tuple[str, str, str]:
    """Return the README text before the block, the block itself, and the text after it."""
    start = text.index(START_MARKER) + len(START_MARKER)
    end = text.index(END_MARKER)
    return text[:start], text[start:end].strip("\n"), text[end:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="Only check that README.md is up to date.")
    args = parser.parse_args()

    text = README_PATH.read_text(encoding="utf-8")
    before, current, after = split_readme(text)
    expected = render()

    if current == expected:
        print("Configuration reference in README.md is up to date.")
        return 0
    if args.check:
        print(
            "Configuration reference in README.md is stale. Run: python scripts/generate_config_reference.py"
        )
        return 1
    README_PATH.write_text(f"{before}\n\n{expected}\n\n{after}", encoding="utf-8")
    print("Configuration reference in README.md updated.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
